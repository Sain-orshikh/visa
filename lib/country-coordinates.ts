const BY_LOWER_NAME = new Map(
  Object.keys(COUNTRY_COORDINATES).map((name) => [name.toLowerCase(), name]),
)

/** Resolves a stored country name to `[lon, lat]`, or null if unrecognised. */
export function countryCoordinates(name: string | null | undefined): [number, number] | null {
  if (!name) return null
  const key = name.trim().toLowerCase()
  const canonical = BY_LOWER_NAME.get(key) ?? ALIASES[key]
  return canonical ? COUNTRY_COORDINATES[canonical] : null
}
